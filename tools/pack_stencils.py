#!/usr/bin/env python3
"""Turn the raw generated images in assets_raw/ into the small coverage masks
the page embeds (src/assets/stencils.js).

Each image is black art on white. The mask is the art: cropped to its
content, scaled to fit 256 px, stored as a 4-bit greyscale PNG.

    python3 tools/pack_stencils.py
"""
import base64, io, os, sys
from PIL import Image, ImageOps

HERE = os.path.dirname(os.path.abspath(__file__))
RAW = os.path.join(HERE, "..", "assets_raw")
OUT = os.path.join(HERE, "..", "src", "assets", "stencils.js")
sys.path.insert(0, HERE)
from gen_stencils import ITEMS, TEXT

SIZE = 256

def pack(path):
    im = Image.open(path).convert("L")
    mask = ImageOps.invert(im)
    # levels: anything paler than light grey is background, anything darker than dark grey is paint
    mask = mask.point(lambda v: 0 if v < 70 else 255 if v > 190 else int((v - 70) * 255 / 120))
    box = mask.point(lambda v: 255 if v > 60 else 0).getbbox()
    if not box:
        return None
    w, h = box[2] - box[0], box[3] - box[1]
    pad = int(max(w, h) * 0.04) + 2
    box = (max(0, box[0] - pad), max(0, box[1] - pad), min(im.width, box[2] + pad), min(im.height, box[3] + pad))
    mask = mask.crop(box)
    s = SIZE / max(mask.size)
    mask = mask.resize((max(8, round(mask.width * s)), max(8, round(mask.height * s))), Image.LANCZOS)
    # a clear one-pixel frame so clamped sampling never smears paint outward
    framed = Image.new("L", (mask.width + 2, mask.height + 2), 0)
    framed.paste(mask, (1, 1))
    framed = framed.point(lambda v: (v >> 4) * 17)          # 16 levels is plenty for an edge
    buf = io.BytesIO()
    framed.convert("P", palette=Image.ADAPTIVE, colors=16).save(buf, "PNG", optimize=True, bits=4)
    return framed.size, buf.getvalue()

def main():
    rows, total = [], 0
    for id_, tmpl, subj, _seed in ITEMS:
        path = os.path.join(RAW, id_ + ".png")
        if not os.path.exists(path):
            print("missing", id_); continue
        r = pack(path)
        if not r:
            print("empty", id_); continue
        (w, h), png = r
        total += len(png)
        name = subj if tmpl is TEXT else id_.replace("-", " ")
        kind = "text" if tmpl is TEXT else "mark"
        rows.append(f'  {{ id: {id_!r}, name: {name!r}, kind: {kind!r}, w: {w}, h: {h}, src: "data:image/png;base64,{base64.b64encode(png).decode()}" }},')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("// Generated by tools/pack_stencils.py from images made with tools/gen_stencils.py. Do not edit by hand.\n")
        f.write("// Coverage masks: white is paint.\nexport const STENCILS = [\n" + "\n".join(rows) + "\n];\n")
    print(f"{len(rows)} stencils, {total/1024:.0f} KB of PNG, {os.path.getsize(OUT)/1024:.0f} KB of source")

if __name__ == "__main__":
    main()

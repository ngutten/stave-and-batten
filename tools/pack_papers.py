#!/usr/bin/env python3
"""Turn the paper scans in assets_raw/ into small grey detail tiles
(src/assets/papers.js): centre crop, large-scale shading removed, mean 0.5.

    python3 tools/pack_papers.py
"""
import base64, io, os
from PIL import Image, ImageFilter, ImageChops, ImageStat

HERE = os.path.dirname(os.path.abspath(__file__))
RAW = os.path.join(HERE, "..", "assets_raw")
OUT = os.path.join(HERE, "..", "src", "assets", "papers.js")
ITEMS = [("parchment", "paper-parchment", 26), ("wash", "paper-wash", 34)]       # name, scan, contrast wanted (standard deviation, 0..255)

def pack(path, gain):
    im = Image.open(path).convert("L")
    w, h = im.size
    # Keep only the tooth of the paper. Anything with a shape of its own (a
    # bloom, a stain, the darkened edge of the sheet) would be recognised
    # every time the tile repeats, so: take the calmest quarter of the scan,
    # and remove everything broader than a few millimetres.
    q = w // 2
    best = None
    for x0 in range(int(w * 0.08), w - q - int(w * 0.08) + 1, max(1, w // 16)):
        for y0 in range(int(h * 0.08), h - q - int(h * 0.08) + 1, max(1, h // 16)):
            c = im.crop((x0, y0, x0 + q, y0 + q))
            rough = ImageStat.Stat(c.filter(ImageFilter.GaussianBlur(12))).stddev[0]
            if best is None or rough < best[0]: best = (rough, c)
    im = best[1].resize((256, 256), Image.LANCZOS)
    low = im.filter(ImageFilter.GaussianBlur(7))
    det = ImageChops.subtract(im, low, 1, 128)
    gain = gain / max(ImageStat.Stat(det).stddev[0], 0.1)
    det = det.point(lambda v: max(0, min(255, int(128 + (v - 128) * gain))))
    buf = io.BytesIO(); det.save(buf, "JPEG", quality=72, optimize=True)
    st = ImageStat.Stat(det)
    return buf.getvalue(), st.mean[0], st.stddev[0]

def main():
    rows = []
    for name, src, gain in ITEMS:
        jpg, mean, sd = pack(os.path.join(RAW, src + ".png"), gain)
        print(f"{name}: {len(jpg)/1024:.1f} KB, mean {mean:.0f}, sd {sd:.1f}")
        rows.append(f'  {name}: "data:image/jpeg;base64,{base64.b64encode(jpg).decode()}",')
    with open(OUT, "w") as f:
        f.write("// Generated by tools/pack_papers.py from scans made with tools/gen_papers.py. Do not edit by hand.\n")
        f.write("// Grey detail tiles: 0.5 is flat paper.\nexport const PAPERS = {\n" + "\n".join(rows) + "\n};\n")

if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Pack the shapes in assets_raw/grunge-*.png into one atlas
(src/assets/grunge.js): four to a row, rows spill / splat / drip, each shape
cropped to its content and fitted into a 128 px cell with a clear margin.

    python3 tools/pack_grunge.py
"""
import base64, io, os
from PIL import Image, ImageOps

HERE = os.path.dirname(os.path.abspath(__file__))
RAW = os.path.join(HERE, "..", "assets_raw")
OUT = os.path.join(HERE, "..", "src", "assets", "grunge.js")
CELL, INNER = 128, 108

def shape(path, top):
    im = ImageOps.invert(Image.open(path).convert("L"))
    im = im.point(lambda v: 0 if v < 70 else 255 if v > 190 else int((v - 70) * 255 / 120))
    box = im.point(lambda v: 255 if v > 60 else 0).getbbox()
    im = im.crop(box) if box else im
    s = INNER / max(im.size)
    im = im.resize((max(4, round(im.width * s)), max(4, round(im.height * s))), Image.LANCZOS)
    cell = Image.new("L", (CELL, CELL), 0)
    # drips hang from the top of their cell; everything else sits in the middle
    cell.paste(im, ((CELL - im.width) // 2, (CELL - INNER) // 2 if top else (CELL - im.height) // 2))
    return cell

def main():
    atlas = Image.new("L", (CELL * 4, CELL * 3), 0)
    for row, kind in enumerate(["spill", "splat", "drip"]):
        for i in range(4):
            atlas.paste(shape(os.path.join(RAW, f"grunge-{kind}-{i}.png"), kind == "drip"), (i * CELL, row * CELL))
    atlas = atlas.point(lambda v: (v >> 4) * 17)
    buf = io.BytesIO(); atlas.convert("P", palette=Image.ADAPTIVE, colors=16).save(buf, "PNG", optimize=True, bits=4)
    atlas.save(os.path.join(RAW, "grunge-atlas-preview.png"))
    with open(OUT, "w") as f:
        f.write("// Generated by tools/pack_grunge.py from shapes made with tools/gen_grunge.py. Do not edit by hand.\n")
        f.write("// Coverage masks, four to a row: spills, splatters, drips.\n")
        f.write(f'export const GRUNGE = "data:image/png;base64,{base64.b64encode(buf.getvalue()).decode()}";\n')
    print(f"atlas {atlas.size}, {len(buf.getvalue())/1024:.1f} KB")

if __name__ == "__main__":
    main()
